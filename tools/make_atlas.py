"""Build the UI atlas (fonts + icons) used by the Wii UI.

usage: python3 tools/make_atlas.py
Reads assets/fonts/Roboto-{Regular,Medium}.ttf, writes src/ui/atlas_data.c and
assets/atlas_preview.png. The order of FONTS and ICONS must match src/ui/atlas.h.
"""
import os

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REG = os.path.join(ROOT, "assets", "fonts", "Roboto-Regular.ttf")
MED = os.path.join(ROOT, "assets", "fonts", "Roboto-Medium.ttf")

FONTS = [  # (file, pixel size) in enum order: META, SMALL, TITLE, BODY, BIG, HUGE
    (REG, 12), (REG, 13), (MED, 14), (REG, 16), (MED, 18), (MED, 24),
]
CHARS = [chr(c) for c in range(32, 127)] + ["•"]  # 127 = bullet
SS = 4  # supersampling for icons


def icon(size, draw_fn):
    big = Image.new("L", (size * SS, size * SS), 0)
    draw_fn(ImageDraw.Draw(big), size * SS)
    return big.resize((size, size), Image.LANCZOS)


def make_icons():
    def circle(d, s):
        d.ellipse((0, 0, s - 1, s - 1), fill=255)

    def corner_inv(d, s):
        d.rectangle((0, 0, s, s), fill=255)
        d.ellipse((0, 0, 2 * s - 1, 2 * s - 1), fill=0)

    def play(d, s):
        d.polygon([(s * 0.22, s * 0.12), (s * 0.22, s * 0.88), (s * 0.88, s * 0.5)], fill=255)

    def pause(d, s):
        d.rectangle((s * 0.2, s * 0.14, s * 0.4, s * 0.86), fill=255)
        d.rectangle((s * 0.6, s * 0.14, s * 0.8, s * 0.86), fill=255)

    def search(d, s):
        w = s * 0.11
        d.ellipse((s * 0.12, s * 0.12, s * 0.66, s * 0.66), outline=255, width=int(w))
        d.line((s * 0.58, s * 0.58, s * 0.88, s * 0.88), fill=255, width=int(w * 1.2))

    def volume(d, s):
        d.polygon([(s * 0.1, s * 0.38), (s * 0.3, s * 0.38), (s * 0.52, s * 0.16), (s * 0.52, s * 0.84),
                   (s * 0.3, s * 0.62), (s * 0.1, s * 0.62)], fill=255)
        w = int(s * 0.07)
        d.arc((s * 0.42, s * 0.3, s * 0.72, s * 0.7), -50, 50, fill=255, width=w)
        d.arc((s * 0.42, s * 0.14, s * 0.92, s * 0.86), -50, 50, fill=255, width=w)

    def back(d, s):
        w = int(s * 0.1)
        d.line((s * 0.2, s * 0.5, s * 0.82, s * 0.5), fill=255, width=w)
        d.line((s * 0.2, s * 0.5, s * 0.48, s * 0.22), fill=255, width=w)
        d.line((s * 0.2, s * 0.5, s * 0.48, s * 0.78), fill=255, width=w)

    arrow = [(0.1, 0.05), (0.1, 0.8), (0.3, 0.62), (0.44, 0.92), (0.56, 0.86), (0.42, 0.57), (0.7, 0.57)]

    def cursor_fill(d, s):
        d.polygon([(x * s, y * s) for x, y in arrow], fill=255)

    def cursor_edge(d, s):
        d.polygon([(x * s, y * s) for x, y in arrow], outline=255, fill=255)
        d.line([(x * s, y * s) for x, y in arrow + arrow[:1]], fill=255, width=int(s * 0.09), joint="curve")

    def ring(d, s):
        d.ellipse((0, 0, s - 1, s - 1), outline=255, width=int(s * 0.12))

    white = Image.new("L", (4, 4), 255)
    return [white, icon(64, circle), icon(32, corner_inv), icon(48, play), icon(48, pause),
            icon(32, search), icon(32, volume), icon(32, back), icon(32, cursor_fill),
            icon(32, cursor_edge), icon(64, ring)]


class Packer:
    def __init__(self, width):
        self.w, self.x, self.y, self.row_h = width, 0, 0, 0

    def place(self, w, h):
        if self.x + w > self.w:
            self.x, self.y, self.row_h = 0, self.y + self.row_h + 1, 0
        pos = (self.x, self.y)
        self.x += w + 1
        self.row_h = max(self.row_h, h)
        return pos

    def height(self):
        return self.y + self.row_h + 1


def main():
    W = 512
    pk = Packer(W)
    pieces = []  # (image, x, y)
    icons = []
    for img in make_icons():
        x, y = pk.place(img.width, img.height)
        pieces.append((img, x, y))
        icons.append((x, y, img.width, img.height))

    fonts = []
    for path, size in FONTS:
        f = ImageFont.truetype(path, size)
        ascent, descent = f.getmetrics()
        glyphs = []
        for ch in CHARS:
            adv = int(round(f.getlength(ch)))
            x0, y0, x1, y1 = f.getbbox(ch, anchor="ls")
            if x1 <= x0 or y1 <= y0:
                glyphs.append((0, 0, 0, 0, 0, 0, adv))
                continue
            g = Image.new("L", (x1 - x0, y1 - y0), 0)
            ImageDraw.Draw(g).text((-x0, -y0), ch, font=f, fill=255, anchor="ls")
            x, y = pk.place(g.width, g.height)
            pieces.append((g, x, y))
            glyphs.append((x, y, g.width, g.height, x0, y0, adv))
        fonts.append((size, ascent, descent, int(round(size * 1.3)), glyphs))

    H = (pk.height() + 3) & ~3
    atlas = Image.new("L", (W, H), 0)
    for img, x, y in pieces:
        atlas.paste(img, (x, y))
    atlas.save(os.path.join(ROOT, "assets", "atlas_preview.png"))

    out = ["/* Generated by tools/make_atlas.py - do not edit. Glyphs: Roboto (Apache-2.0). */",
           '#include "atlas.h"', "",
           f"const int atlas_w = {W}, atlas_h = {H};",
           f"const unsigned char atlas_i8[{W * H}] = {{"]
    data = atlas.tobytes()
    for i in range(0, len(data), 32):
        out.append("    " + ",".join(str(b) for b in data[i:i + 32]) + ",")
    out.append("};\n")
    out.append("const atlas_font atlas_fonts[FONT_COUNT] = {")
    for size, asc, desc, lh, glyphs in fonts:
        out.append(f"    {{ {size}, {asc}, {desc}, {lh}, {{")
        for g in glyphs:
            out.append("        { %d, %d, %d, %d, %d, %d, %d }," % g)
        out.append("    } },")
    out.append("};\n")
    out.append("const atlas_rect atlas_icons[ICON_COUNT] = {")
    for r in icons:
        out.append("    { %d, %d, %d, %d }," % r)
    out.append("};")
    with open(os.path.join(ROOT, "src", "ui", "atlas_data.c"), "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"atlas {W}x{H}, {len(pieces)} pieces")


if __name__ == "__main__":
    main()
