"""Make the WiiTube logo assets from the source artwork.

usage: python3 tools/make_logo.py assets/logo_source.webp

Writes:
  assets/logo.png                 transparent, cropped, full size (for docs)
  wii/icon.png                    128x48 Homebrew Channel icon
  src/platform/wii/logo_data.c    small RGBA copies drawn by the app (header + splash)

The white background (and the light shadow under the logo) is removed by flood-filling
from the image border, so white areas inside the logo (the "Tube" letters) stay solid.
"""
import os
import sys

from PIL import Image, ImageChops, ImageDraw, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MARK = (1, 2, 3)  # colour used to tag background pixels during the flood fill


def pixels(img):
    """All pixels in order (Pillow 12 renamed getdata to get_flattened_data)."""
    get = getattr(img, "get_flattened_data", None) or img.getdata
    return list(get())


def transparent(src):
    rgb = src.convert("RGB")
    w, h = rgb.size
    tagged = rgb.copy()
    # Seeds all around the border; threshold = sum of channel differences from the seed
    # (white): catches the white background and the light grey drop shadow, but not the
    # grey letters (~165) or the pink anti-aliasing of the red box.
    seeds = [(x, y) for x in range(0, w, 16) for y in (0, h - 1)]
    seeds += [(x, y) for y in range(0, h, 16) for x in (0, w - 1)]
    for xy in seeds:
        if tagged.getpixel(xy) != MARK:
            ImageDraw.floodfill(tagged, xy, MARK, thresh=90)

    bg = Image.new("L", (w, h), 0)
    bg.putdata([255 if p == MARK else 0 for p in pixels(tagged)])
    near = ImageChops.subtract(bg.filter(ImageFilter.MaxFilter(25)), bg)  # ~12 px band

    out = Image.new("RGBA", (w, h))
    px_out = []
    for (r, g, b), is_bg, is_near in zip(pixels(rgb), pixels(bg), pixels(near)):
        if is_bg:
            px_out.append((0, 0, 0, 0))
            continue
        if not is_near:
            px_out.append((r, g, b, 255))
            continue
        hi, lo = max(r, g, b), min(r, g, b)
        if hi - lo < 30:
            # Grey edge pixel: letters (~165) stay solid, lighter anti-aliasing fades out.
            a = (240 - (r + g + b) / 3) / (240 - 185)
            a = max(0.0, min(1.0, a))
            px_out.append((r, g, b, int(a * 255 + 0.5)))
        else:
            # Coloured edge pixel blended with white: remove the white ("colour to alpha").
            a = (255 - lo) / 255
            if a <= 0.01:
                px_out.append((0, 0, 0, 0))
                continue
            un = lambda c: int(max(0, min(255, (c - 255 * (1 - a)) / a)) + 0.5)
            px_out.append((un(r), un(g), un(b), int(a * 255 + 0.5)))
    out.putdata(px_out)
    box = out.getchannel("A").point(lambda v: 255 if v > 8 else 0).getbbox()
    pad = 4
    box = (max(0, box[0] - pad), max(0, box[1] - pad), min(w, box[2] + pad), min(h, box[3] + pad))
    return out.crop(box)


def resize(img, width=None, height=None):
    w, h = img.size
    if width is None:
        width = max(1, round(w * height / h))
    if height is None:
        height = max(1, round(h * width / w))
    # Resample premultiplied so transparent pixels don't bleed dark fringes.
    return img.convert("RGBa").resize((width, height), Image.LANCZOS).convert("RGBA")


def c_array(name, img):
    w, h = img.size
    data = img.tobytes()
    lines = [f"const int {name}_w = {w}, {name}_h = {h};",
             f"const unsigned char {name}_rgba[{w * h * 4}] = {{"]
    for i in range(0, len(data), 24):
        lines.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    src = Image.open(sys.argv[1])
    logo = transparent(src)
    os.makedirs(os.path.join(ROOT, "assets"), exist_ok=True)
    logo.save(os.path.join(ROOT, "assets", "logo.png"), optimize=True)

    # Homebrew Channel icon: exactly 128x48, logo centred.
    icon = Image.new("RGBA", (128, 48), (0, 0, 0, 0))
    fit = resize(logo, width=124) if logo.width / logo.height > 124 / 44 else resize(logo, height=44)
    icon.alpha_composite(fit, ((128 - fit.width) // 2, (48 - fit.height) // 2))
    icon.save(os.path.join(ROOT, "wii", "icon.png"), optimize=True)

    small = resize(logo, height=40)   # menu header
    splash = resize(logo, width=288)  # startup / loading screens
    with open(os.path.join(ROOT, "src", "platform", "wii", "logo_data.c"), "w") as f:
        f.write("/* Generated by tools/make_logo.py from assets/logo_source.webp - do not edit. */\n")
        f.write(c_array("logo_small", small) + "\n\n")
        f.write(c_array("logo_splash", splash) + "\n")
    print("logo", logo.size, "icon 128x48", "small", small.size, "splash", splash.size)


if __name__ == "__main__":
    main()
